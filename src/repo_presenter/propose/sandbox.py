#: Words a sandbox pull request body must never carry (attribution / provenance wording).
FORBIDDEN_BODY_WORDS = (
    "attribution", "provenance", "generated by", "proposed by", "written by", "authored by",
    "repository-presenter", "candidate_hash", "policy_version", "not verified by the maintainer",
)


def sandbox_branch(entry: SandboxEntry, candidate_repository: str, lane: str, readme_sha256: str) -> str:
    owner, name = candidate_repository.split("/", 1)
    return f"{entry.branch_prefix}{owner}__{name}-{lane.lower()}-{readme_sha256[:12]}"


def compose_sandbox_pull_request(
    *,
    candidate_repository: str,
    lane: str,
    candidate_readme: str,
    live_readme: str | None,
    source_revision: str,
    readme_sha256: str,
    sandbox_path: str,
    evidence: PullRequestEvidence,
    live_read: bool = True,
) -> PullRequestContent:
    """A factual title and body: what the file is, where it sits, how it differs from the live README and what
    the sealed bundle recorded. No attribution, no provenance footer."""
    product = product_name(candidate_readme, candidate_repository)
    changes = diff_sections(live_readme or "", candidate_readme)
    if not live_read:
        compared = "- Compared with the live README: not compared (the live README was not read)."
    elif live_readme is None:
        compared = "- Compared with the live README: the repository has none."
    elif changes.count == 0:
        compared = "- Compared with the live README: no section differs."
    else:
        parts = [
            f"{label} ({len(items)}): " + ", ".join(items[:10])
            for label, items in (("rewritten", changes.updated), ("new", changes.added), ("removed", changes.removed))
            if items
        ]
        compared = "- Compared with the live README: " + "; ".join(parts) + "."
    body = "\n".join(
        [
            f"Sandbox copy of a README candidate for **{product}** (`{candidate_repository}`, lane {lane}).",
            "",
            f"- Source revision: `{source_revision[:12]}`",
            f"- File in this pull request: `{sandbox_path}`",
            f"- README SHA-256: `{readme_sha256}`",
            f"- Size: {len(candidate_readme.encode('utf-8'))} bytes"
            + (f"; {changes.lines_added} lines added and {changes.lines_removed} removed against the live README." if live_read and live_readme is not None else "."),
            compared,
            *_verified_lines(evidence),
            "",
            f"Only `{sandbox_path}` is added. This repository's own `README.md` and every other file are untouched. "
            "This is a draft for review; close it without merging when done.",
            "",
        ]
    )
    lowered = body.lower()
    hit = next((w for w in FORBIDDEN_BODY_WORDS if w in lowered), None)
    if hit is not None:  # a defence for a future edit of the template, never reached with today's text
        raise ValueError(f"sandbox pull request body must not carry {hit!r}")
    return PullRequestContent(title=f"sandbox: README candidate for {product} (lane {lane})", body=body)


def propose_sandbox(
    *,
    candidate_repository: str,
    lane: str,
    readme_text: str,
    source_revision: str,
    sandbox_base_branch: str,
    token: str | None,
    environment: Mapping[str, str],
    review: ReviewVerdict,
    acceptance_records: Sequence[AttestedAcceptance],
    compose: Callable[[str | None, str, str], PullRequestContent],
    live_readme_of_candidate: Callable[[], str | None],
    recheck_source: Callable[[], str],
    readme_bytes_sha256: str | None = None,
    entry: SandboxEntry | None = None,
    verify_token: Callable[..., object] = default_verify_installation_token,
    verify_pull_request_app: Callable[..., object] = default_verify_pull_request_app,
    get_ref: Callable[..., "str | None"] = default_get_ref,
    create_ref: Callable[..., None] = default_create_ref,
    get_contents: Callable[..., "FileContents | None"] = default_get_contents,
    put_contents: Callable[..., object] = default_put_contents,
    find_pull_requests: Callable[..., "tuple[PullRequestRef, ...]"] = default_find_pull_requests,
    create_pull_request: Callable[..., PullRequestRef] = default_create_pull_request,
    sandbox_data: Path | None = None,
) -> ProposalEffectResult:
    """Open one draft pull request in the sandbox for ``candidate_repository``'s README - past every gate in this
    module's docstring. Every early return makes no write call, and the gates before the token check make no
    network call at all."""
    sandbox = sandbox_repository(environment, *( (sandbox_data,) if sandbox_data else () ))
    branch = ""

    def refuse(authorized: bool, code: Refusal, reason: str, **extra: object) -> ProposalEffectResult:
        return ProposalEffectResult(
            repository=sandbox or "",
            authorized=authorized,
            effected=False,
            branch=branch,
            pr_number=extra.get("pr_number"),  # type: ignore[arg-type]
            pr_url=extra.get("pr_url"),  # type: ignore[arg-type]
            commit_written=bool(extra.get("commit_written")),
            pr_created=bool(extra.get("pr_created")),
            pr_updated=False,
            reason=reason,
            reason_code=code,
        )

    if sandbox is None:
        return refuse(
            False,
            Refusal.SANDBOX_NOT_SELECTED,
            f"no sandbox is selected: {SANDBOX_VARIABLE} must name the sandbox repository exactly "
            "(unset, another repository and the wildcard select none)",
        )
    try:
        entry = entry or load_sandbox_entry(*((sandbox_data,) if sandbox_data else ()))
    except SandboxConfigError as exc:
        return refuse(False, Refusal.SANDBOX_NOT_SELECTED, str(exc))
    if "pull_request" not in entry.effects:
        return refuse(False, Refusal.SANDBOX_NOT_SELECTED, "the sandbox entry does not grant pull_request")
    owner, name = sandbox.split("/", 1)
    sandbox_path = entry.readme_path(candidate_repository)
    if not sandbox_path.startswith("sandbox/") or sandbox_path.lower() == "readme.md":
        return refuse(False, Refusal.SANDBOX_NOT_SELECTED, f"refusing sandbox path {sandbox_path!r}")
    digest = readme_bytes_sha256 or bytes_sha256(readme_text)
    branch = sandbox_branch(entry, candidate_repository, lane, digest)
    if not branch.startswith(entry.branch_prefix):
        return refuse(False, Refusal.SANDBOX_NOT_SELECTED, f"refusing sandbox branch {branch!r}")

    if not write_authorized(environment):
        return refuse(False, Refusal.WRITE_NOT_ENABLED, "not authorized: REPO_PRESENTER_PROPOSAL_WRITE_AUTHORIZED is not set to a truthy value")
    if review.verdict != "ACCEPT" or not review.model_reviewed:
        return refuse(True, Refusal.REVIEW_REJECTED, "the independent review is not an ACCEPT by a model review; never proposed")
    verdict = evaluate_acceptance(
        acceptance_records,
        repository=candidate_repository,
        lane=lane,
        revision=source_revision,
        readme_bytes_sha256=digest,
        classify_fn=classify,
    )
    if verdict.state not in PUBLISHABLE_STATES:
        return refuse(
            True,
            Refusal.ACCEPTANCE_NOT_CERTIFIED,
            f"the acceptance contract classifies this candidate as {verdict.state!r}, not one of "
            f"{sorted(PUBLISHABLE_STATES)}" + (f" ({verdict.detail})" if verdict.detail else ""),
        )
    if not token:
        return refuse(True, Refusal.NO_WRITE_TOKEN, "no write-scoped token available (GH_PROPOSAL_WRITE_TOKEN, never GH_TOKEN)")
    token_decision = verify_token(sandbox, token)
    if not getattr(token_decision, "ok", False):
        return refuse(
            True,
            getattr(token_decision, "code", None) or Refusal.TOKEN_UNVERIFIABLE,
            str(getattr(token_decision, "reason", "token not verified")),
        )
    live_revision = recheck_source()
    if live_revision != source_revision:
        return refuse(
            True,
            Refusal.SOURCE_MOVED,
            f"stale source: {candidate_repository} is now at {live_revision}, the candidate was sealed at {source_revision}",
        )

    try:
        prs = find_pull_requests(owner, name, head_branch=branch, token=token)
    except RepositoryMetadataError as exc:
        return refuse(True, Refusal.GITHUB_ERROR, f"could not list pull requests for {branch!r}: {exc}")
    if prs:
        found = prs[0]
        return refuse(
            True,
            Refusal.PR_DUPLICATE,
            f"pull request #{found.number} ({found.url}, {found.state}) already exists for this exact candidate "
            f"on {branch}; it is not recreated or updated",
            pr_number=found.number,
            pr_url=found.url,
        )

    try:
        base_sha = get_ref(owner, name, sandbox_base_branch, token=token)
        if base_sha is None:
            return refuse(True, Refusal.GITHUB_ERROR, f"sandbox base branch {sandbox_base_branch!r} does not exist")
        branch_sha = get_ref(owner, name, branch, token=token)
        if branch_sha is None:
            create_ref(owner, name, branch, base_sha, token=token)
        existing = get_contents(owner, name, sandbox_path, ref=branch, token=token)
    except RepositoryMetadataError as exc:
        return refuse(True, Refusal.GITHUB_ERROR, f"sandbox branch preparation failed: {exc}")

    content = compose(live_readme_of_candidate(), sandbox_path, digest)
    commit_written = False
    if existing is None or existing.text != readme_text:
        try:
            put_contents(
                owner,
                name,
                sandbox_path,
                branch=branch,
                message=f"sandbox: README candidate for {candidate_repository} (lane {lane})",
                text=readme_text,
                sha=existing.sha if existing is not None else None,
                token=token,
            )
            commit_written = True
        except RepositoryMetadataError as exc:
            return refuse(True, Refusal.GITHUB_ERROR, f"could not write {sandbox_path} on {branch!r}: {exc}")
    try:
        pr = create_pull_request(
            owner, name, title=content.title, body=content.body, head=branch, base=sandbox_base_branch,
            token=token, draft=True,
        )
    except RepositoryMetadataError as exc:
        return refuse(True, Refusal.GITHUB_ERROR, f"could not open the sandbox pull request: {exc}", commit_written=commit_written)
    attribution = verify_pull_request_app(owner, name, pr.number, token=token)
    if not getattr(attribution, "ok", False):
        return refuse(
            True,
            getattr(attribution, "code", None) or Refusal.TOKEN_UNVERIFIABLE,
            f"{getattr(attribution, 'reason', 'pull request not attributed to the App')} - review and close {pr.url} if it is not ours",
            pr_number=pr.number,
            pr_url=pr.url,
            commit_written=commit_written,
            pr_created=True,
        )
    return ProposalEffectResult(
        repository=sandbox,
        authorized=True,
        effected=True,
        branch=branch,
        pr_number=pr.number,
        pr_url=pr.url,
        commit_written=commit_written,
        pr_created=True,
        pr_updated=False,
        reason="sandbox draft pull request opened",
    )


