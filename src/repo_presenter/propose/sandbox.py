"""The R17 sandbox write path (owner decision 2026-11-22: the sandbox is ``babar-raza/repo-presenter`` itself).

R17: the upstream-write mechanics are proven on an owner-owned sandbox BEFORE R15 holds. ``propose_candidate``
cannot serve that purpose: it binds the write permit, the authorization record and the README path to ONE target
repository, and writes ``README.md``. Here the candidate belongs to some upstream repository and the write target is
the sandbox, so this is a separate, narrower effect:

* the sandbox is selected only by the repository variable ``REPO_PRESENTER_PROPOSE_SANDBOX_REPOSITORY`` naming the
  exact repository in ``data/sandbox_write_target.json`` (``sandbox_scope``); unset, another repository or ``*`` is
  refused before any call;
* the same candidate gates as the upstream effect run first and unchanged: the owner kill switch
  (``REPO_PRESENTER_PROPOSAL_WRITE_AUTHORIZED``), the independent review's ACCEPT by a model, gate 3b (the real
  acceptance classifier over the attested, content-bound record), the write token, token provenance (the
  installation token reaches exactly the sandbox) and source freshness. The R15 portfolio predicate is NOT required
  here (that is the point of R17); it stays required for every other target in ``propose/run.py`` and at the
  transport guard (``github/client.authorize_write``);
* the candidate README is written ONLY under the entry's ``sandbox_path_template`` (``sandbox/<owner>__<repo>/
  README.md``), never over the sandbox repository's own README, on a throwaway branch under ``sandbox_branch_prefix``
  that names the candidate repository, lane and the first 12 characters of the README's hash;
* the pull request is always a DRAFT, authored by the repository-presenter App (verified), with a factual body that
  carries no attribution or provenance wording (R9 is a README rule; PR bodies are kept factual as well);
* duplicates are refused: a pull request (open, closed or merged) from the same throwaway branch is never recreated
  and never updated; a branch that exists without a pull request (an earlier write that stopped midway) is completed.

No authorization record is required: that record (merge-before-run provenance) protects an upstream maintainer, and
the sandbox is the owner's own repository, selected by the owner's variable.
"""

