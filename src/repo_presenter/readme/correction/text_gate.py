"""What inserted text may say: no internal-assurance narration.

``engine.collect`` drops any edit whose inserted text still carries internal-assurance vocabulary
("verified against this revision", "source revision", "provider call", ...) after subtracting
whatever the replaced text already said — plans/idea.md: "Never present: internal assurance
narration". ``narration`` reports whatever of that vocabulary is left.

Ported (REUSE, narrow slice) from the old repository's ``components/readme_correction/text_gate.py``
and the phrase list it reads from ``components/readme/validation/registry.py::narration_patterns``.
Only the phrase list and its two pattern-building functions are ported here — small (11 phrases,
stdlib ``re`` only, no entanglement) — not the surrounding ``validation/registry.py`` module itself,
which is part of the acceptance/validator chain `docs/MISSION_AUTHORITY.md` restricts to ADAPT/
FIXTURE_ONLY at most (the module this narration list lives in also defines claim/fence/host
machinery for the BC-04/BC-14 validators this repository has not re-verified).

``text_gate.clean`` (strips the *renderer's own* evidence phrasings, e.g. ", verified against this
revision") is NOT ported in this pass: its three callers in the old repo (``sections.py``,
``additions.py``, both deferred — see ``migration/reuse-manifest.yaml``) are not ported either, so
there is nothing here that would call it yet.
"""

from __future__ import annotations

import re
from collections.abc import Collection

#: Every narration phrase this path refuses, in the old repo's own hand-curated, fitted-to-
#: observed-cases catalog (plans/idea.md: "Source revisions, isolated-build conditions, network
#: policy, registry receipts, provider calls, evidence collectors, and validation status belong in
#: evidence"). Zero tolerance: one occurrence blocks (the contract states no count threshold).
_NARRATION: tuple[str, ...] = (
    "preserved repository details",
    "other platforms",
    "provider call",
    "source revision",
    "validator",
    "isolated build",
    "fact id",
    "generated by",
    "this readme was",
    "real, verified",
    "network policy",
    "registry receipt",
    "evidence collector",
    "validation status",
    "this revision",
)
#: How plans/idea.md spells the evidence vocabulary it lists: a plural, a hyphen for a space
#: ("isolated-build conditions"), and "policies" -- a bare word-bounded phrase would miss every
#: plural or hyphenated form the idea text itself uses.
_NARRATION_FORMS: dict[str, str] = {
    "source revision": r"source[ -]revisions?",
    "isolated build": r"isolated[ -]builds?",
    "provider call": r"provider[ -]calls?",
    "network policy": r"network[ -]polic(?:y|ies)",
    "registry receipt": r"registry[ -]receipts?",
    "evidence collector": r"evidence[ -]collectors?",
    "validation status": r"validation[ -]status",
    "this revision": r"(?:at|for|against|on)\s+this\s+revision",
}
#: "generated by" needs an allowlist-of-safe-nouns exemption the others don't: a real noun this
#: repository's own surface names (a public type, a tool it genuinely wraps) is a true technical
#: claim, never narration, and is never flagged. Only the pipeline's own literal name, or "this/the"
#: plus one of this small closed set of self-referential nouns, narrates.
_SELF_REFERENTIAL_GENERATED_BY_NOUNS: tuple[str, ...] = (
    "tool",
    "pipeline",
    "process",
    "document",
    "readme",
)


def _generated_by_pattern() -> re.Pattern[str]:
    nouns = "|".join(sorted(re.escape(noun) for noun in _SELF_REFERENTIAL_GENERATED_BY_NOUNS))
    return re.compile(rf"\bgenerated by\b\s+(?:repository-presenter|(?:this|the)\s+(?:{nouns}))\b")


def narration_patterns(
    symbol_names: Collection[str],  # noqa: ARG001 -- kept for signature parity with the old repo
) -> tuple[tuple[str, re.Pattern[str]], ...]:
    """Every narration phrase's pattern, per candidate; ``symbol_names`` is accepted but unused
    (the old repo's own ``_generated_by_pattern`` no longer reads it either -- see its docstring)."""
    return tuple(
        (
            phrase,
            _generated_by_pattern()
            if phrase == "generated by"
            else re.compile(rf"\b{_NARRATION_FORMS.get(phrase, re.escape(phrase))}\b"),
        )
        for phrase in _NARRATION
    )


#: A second, smaller catalog the old repo's own ``text_gate.py`` (not ``validation/registry.py``)
#: added directly, case-insensitively and not anchored to the idea.md plural/hyphen forms above.
_EXTRA: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("this revision", re.compile(r"\bthis revision\b", re.IGNORECASE)),
    ("verified against", re.compile(r"\bverified (?:against|at|in isolation)\b", re.IGNORECASE)),
    ("evidence", re.compile(r"\bevidence\b", re.IGNORECASE)),
    ("manifest key", re.compile(r"\b(?:declared|read) (?:in|from) `[^`]+`\b")),
)


def narration(text: str) -> list[str]:
    """The internal-assurance phrases ``text`` still carries (empty when it is fit to publish)."""
    found = [phrase for phrase, pattern in narration_patterns(()) if pattern.search(text)]
    found += [name for name, pattern in _EXTRA if pattern.search(text) and name not in found]
    return found
