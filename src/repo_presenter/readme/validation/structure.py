# The shell heading levels a heading may take: (level, is a shell heading, is a prescribed subheading).
HEADING_OK = frozenset({(2, True, False), (3, False, True), (4, False, True)})
EXAMPLE_N = re.compile(r"(?i)example\s*\d+")
BADGE_TOKEN = r"(?:\[!\[[^\]]*\]\([^)]*\)\]\([^)]*\)|!\[[^\]]*\]\([^)]*\))"
BADGE_ROW = re.compile(rf"{BADGE_TOKEN}(?: {BADGE_TOKEN})*")
GLANCE_FENCE = re.compile(r"```mermaid\n.*?\n```", re.DOTALL)
DETAILS_OPEN = re.compile(r"(?i)<details\b")
DETAILS_CLOSE = re.compile(r"(?i)</details\s*>")
RENDERER_OWNER = "D"  # shell sections the renderer owns, not the authoring stage
NAME_SEPARATOR = r"[\s._-]*"
# The words that make a no-space spelling a technical identifier rather than the product name.
IDENTIFIER_CUE_BEFORE = re.compile(
    r"(?i)\b(?:package|namespace|assembly|module|crate|named|called)\s+(?:`)?$"
)
IDENTIFIER_CUE_AFTER = re.compile(
    r"(?i)^(?:`)?\s+(?:version|package|namespace|assembly|module|crate)\b"
)
# What makes a no-space match part of a LONGER identifier: a qualified-name or file-extension
# continuation, a path or scope separator after it, or the same before it.
IDENTIFIER_CONTINUES = re.compile(r"^(?:\.[A-Za-z_]|[/\\]|::)")
IDENTIFIER_CONTINUED = re.compile(r"(?:[A-Za-z0-9_]\.|[/\\]|::)$")
DOTTED_SEGMENT = re.compile(r"^\.([A-Za-z_][A-Za-z0-9_]*)")


def _heading_case_failures(
    line: str, text: str, forms: dict[str, str], section: str | None
) -> list[Failure]:
    """plans/idea.md: every Markdown heading uses title case, and visitor-facing technical
    abbreviations use their canonical uppercase forms throughout, whatever the heading's level."""
    failures = [
        Failure(
            "COMPOSING",
            f"heading {line!r}: abbreviation {found!r} is not in its canonical form {canonical}",
            section,
        )
        for found, canonical in noncanonical_terms(text, forms)
    ]
    wrong = title_case_violations(text, forms)
    if wrong:
        failures.append(
            Failure(
                "COMPOSING",
                f"heading {line!r} is not in title case: {', '.join(repr(w) for w in wrong)}",
                section,
            )
        )
    return failures


def _collapsed_section_failures(readme: str) -> list[Failure]:
    """plans/idea.md and README_CONTRACT.md row 17: a section the shell marks ``visible`` never
    renders inside a ``<details>`` block, because a visitor who has not clicked would not see it."""
    visible = {
        section.heading: section.id
        for section in SEMANTIC_SHELL
        if section.heading and section.visibility == "visible"
    }
    failures: list[Failure] = []
    depth = 0
    for line, _section in outside_lines(readme):
        if depth > 0 and line.startswith("## "):
            heading = line[3:].strip()
            if heading in visible:
                failures.append(
                    Failure(
                        "COMPOSING",
                        f"visible section {heading!r} renders inside a collapsed <details> block",
                    )
                )
        depth = max(
            0,
            depth + len(DETAILS_OPEN.findall(line)) - len(DETAILS_CLOSE.findall(line)),
        )
    return failures


def _fence_and_spacing_failures(candidate: Candidate) -> list[Failure]:
    """plans/idea.md: every source fence carries its language and visitor examples use normalized
    spacing with no repeated empty-line run. A placed inherited code block is exempt from both:
    check 8 requires it to render exactly as the upstream wrote it."""
    verbatim_bodies = {
        fence_body(placement.text)[1].strip()
        for placement in placements_of(candidate)
        if placement.outcome == "placed" and placement.unit_id.endswith(".code_block")
    }
    failures: list[Failure] = []
    for token in MarkdownIt("commonmark").parse(candidate.readme):
        if token.type != "fence" or token.content.strip() in verbatim_bodies:
            continue
        line = (token.map[0] + 1) if token.map else 0
        if not token.info.strip():
            failures.append(
                Failure("COMPOSING", f"code fence at line {line} has no language")
            )
        body = token.content.rstrip("\n")
        if collapse_blank_runs(body) != body:
            failures.append(
                Failure(
                    "COMPOSING",
                    f"code fence at line {line} has a repeated empty-line run",
                )
            )
    blank = 0
    inside = False
    for number, text in enumerate(candidate.readme.splitlines(), start=1):
        stripped = text.strip()
        if stripped.startswith("```") and not inside:
            inside = True
        elif stripped == "```" and inside:
            inside = False
        if inside or stripped.startswith("```"):
            blank = 0
        elif not stripped:
            blank += 1
            if blank == 2:
                failures.append(
                    Failure(
                        "COMPOSING", f"repeated empty-line run ending at line {number}"
                    )
                )
        else:
            blank = 0
    return failures


def _reference_failures(candidate: Candidate) -> list[Failure]:
    """A sentence that points at a table, list, example or section the README does not have
    (composition/references.py). A sentence a placed inherited unit carries was kept while its
    referent was dropped or moved, which only reconciliation can undo (RECONCILING, naming the
    unit); any other sentence is authored prose, routed to the section that holds it (COMPOSING).

    ``unit`` is passed to ``Failure``'s own ``unit`` field, not only interpolated into ``detail``:
    a real hosted Lane R run (aspose-cells-foss/Aspose.Cells-FOSS-for-Rust, run 40688097016) hit a
    RECONCILING finding here that named its unit in the message text yet the patch router
    (``reconciliation/patch.py::failing_units``) read ``unit_id`` from ``Failure`` fields only --
    by design (``validation/failures.py``'s ``Failure`` docstring: "never prose parsed back out of
    ``detail``") -- so the one field this function forgot to set made the unit structurally
    unnamed and the S4 patch repair fell back to "no stored disposition ... is named by this
    defect", exactly as if the check had never known which unit it was."""
    placed = [
        (p.unit_id, normalized(p.text))
        for p in placements_of(candidate)
        if p.outcome == "placed"
    ]
    sections = section_texts(candidate.readme)
    failures: list[Failure] = []
    for reference in dangling_references(candidate.readme):
        sentence = normalized(reference.sentence)
        unit = next(
            (unit_id for unit_id, text in placed if sentence in " ".join(text.split())),
            None,
        )
        located_in = next(
            (
                sid
                for sid, text in sections.items()
                if sentence in " ".join(text.split())
            ),
            None,
        )
        if unit is not None:
            failures.append(
                Failure(
                    "RECONCILING",
                    f"{unit} is kept as written but {reference.reason}: "
                    f"{reference.sentence[:140]!r}",
                    located_in,
                    unit=unit,
                )
            )
        else:
            failures.append(
                Failure(
                    "COMPOSING",
                    f"dangling reference: {reference.reason}: {reference.sentence[:140]!r}",
                    located_in,
                )
            )
    return failures


def _narration_failures(
    readme: str,
    prose_text: str,
    symbol_names: set[str],
    inherited: str,
    docstrings: str,
) -> list[Failure]:
    """plans/idea.md: internal assurance narration never appears in the document. A phrase that is
    itself a SUPPORTED public symbol's name, a phrase the upstream README already used, or a phrase
    inside a public symbol's own docstring is the repository's own vocabulary, not the pipeline's."""
    lowered = prose_text.lower()
    matched = [
        phrase
        for phrase, pattern in narration_patterns(symbol_names)
        if pattern.search(lowered)
        and phrase not in symbol_names
        and not pattern.search(inherited)
        and not pattern.search(docstrings)
    ]
    if not matched:
        return []
    llm_owned = {
        section.id for section in SEMANTIC_SHELL if section.owner != RENDERER_OWNER
    }
    section_prose = {
        section_id: prose(text.splitlines()).lower()
        for section_id, text in section_texts(readme).items()
        if section_id in llm_owned
    }
    patterns_by_phrase = dict(narration_patterns(symbol_names))
    failures: list[Failure] = []
    for phrase in matched:
        pattern = patterns_by_phrase[phrase]
        located_in = next(
            (sid for sid, text in section_prose.items() if pattern.search(text)), None
        )
        failures.append(
            Failure("COMPOSING", f"internal narration {phrase!r}", located_in)
        )
    return failures


def structure_failures(candidate: Candidate) -> list[Failure]:
    """BC-07: one factual H1; one badge row in the stable order, each badge supported by a verified
    fact; title-case headings at every level; canonical abbreviations in prose and headings; fence
    languages and normalized spacing; visible sections never collapsed; the At a Glance graph is one
    fence and nothing else; no internal narration; dangling references named; within the length
    budget. The At a Glance geometry sub-check is not run (see the module docstring)."""
    failures: list[Failure] = []
    name = product_name(candidate.entry)
    outside = outside_fences(candidate.readme)
    h1 = [line for line in outside if line.startswith("# ")]
    if h1 != [f"# {name}"]:
        failures.append(
            Failure(
                "COMPOSING", f"expected exactly one H1 {'# ' + name!r}; found {len(h1)}"
            )
        )
    # The banner is one linked image from the verified illustration and homepage facts, immediately
    # below the badge row; it is not a second badge row.
    banner = ""
    pair = banner_target(candidate.facts.facts)
    if pair is not None:
        banner = f"[![{name}]({pair[0].value})]({pair[1].value})"
    badge_rows = [
        line
        for line in outside
        if BADGE_ROW.fullmatch(line.strip()) and line.strip() != banner
    ]
    if len(badge_rows) != 1:
        # A repository with no packaging metadata carries no fact any badge slot could render from;
        # zero badges is then the correct, complete render. Any badge-worthy fact present and still
        # no rendered row is a real composition defect.
        contributors = contributors_target(candidate.entry.repository).casefold()
        badge_worthy = any(
            fact.kind in ("package", "license")
            or (
                fact.kind == "link_target"
                and (
                    fact.id == CI_BADGE_FACT_ID or fact.value.casefold() == contributors
                )
            )
            for fact in candidate.facts.facts
        )
        if badge_rows or badge_worthy:
            failures.append(
                Failure("COMPOSING", f"expected one badge row; found {len(badge_rows)}")
            )
    else:
        # The expected row is what the renderer derives from the facts, in the stable order.
        expected = badge_slots(
            RenderContext(
                candidate.entry,
                candidate.facts,
                candidate.plan,
                candidate.units,
                candidate.dispositions,
            )
        )
        failures.extend(
            Failure("COMPOSING", problem, "badges")
            for problem in badge_problems(badge_rows[0].strip(), expected)
        )
    # Every verified public type exactly once, keyed by its canonical defining location, and the
    # Core API table lists those types and nothing else.
    types = [
        fact
        for fact in candidate.facts.by_kind("public_symbol")
        if fact.polarity == "SUPPORTED"
        and (fact.attributes or {}).get("symbol_kind") in {"class", "enum"}
    ]
    locations = Counter(
        (fact.attributes or {}).get("defined_at") or fact.value for fact in types
    )
    for location, count in sorted(locations.items()):
        if count > 1:
            failures.append(
                Failure(
                    "EXTRACTING",
                    f"verified public type {location} is recorded {count} times; one fact per "
                    "canonical defining location",
                )
            )
    rows = re.findall(
        r"^\| `([^`]+)` \|",
        section_texts(candidate.readme).get("api_reference", ""),
        re.MULTILINE,
    )
    if rows and len(rows) != len(types):
        failures.append(
            Failure(
                "COMPOSING",
                f"the Core API table lists {len(rows)} rows for {len(types)} verified public types",
            )
        )
    headings = {section.heading for section in SEMANTIC_SHELL if section.heading}
    # Additional Examples holds every further example under its own real, unique, task-named
    # level-three heading: never "Example N", never reused.
    tasks = [
        line[4:].strip()
        for line in section_texts(candidate.readme)
        .get("additional_examples", "")
        .splitlines()
        if line.startswith("### ")
    ]
    for task, count in Counter(tasks).items():
        if count > 1:
            failures.append(Failure("COMPOSING", f"example heading {task!r} is reused"))
        if EXAMPLE_N.fullmatch(task):
            failures.append(
                Failure("COMPOSING", f"example heading {task!r} names no task")
            )
    # The Detailed Member Reference groups members under the names the renderer itself gives the
    # hub types, read from its one function rather than re-derived here.
    topics = set(api_reference_names(candidate.facts).values())
    api_lines = set(
        section_texts(candidate.readme).get("api_reference", "").splitlines()
    )
    forms = canonical_abbreviations(candidate.facts)
    owned = {
        section.id for section in SEMANTIC_SHELL if section.owner != RENDERER_OWNER
    }
    for line, section_id in outside_lines(candidate.readme):
        if line.startswith("#") and not line.startswith("# "):
            level = len(line) - len(line.lstrip("#"))
            text = line.lstrip("#").strip()
            # An API Reference topic is a type's own name (a code identifier), judged neither as
            # English nor as an abbreviation.
            identifier = level == 3 and line in api_lines and text in topics
            known = (
                (level == 3 and text in tasks)
                or identifier
                or (level, text in headings, text in SUBSECTION_HEADINGS) in HEADING_OK
            )
            if not known:
                failures.append(
                    Failure(
                        "COMPOSING",
                        f"heading {line!r} is not a shell heading in title case",
                    )
                )
            if not identifier:
                failures.extend(
                    _heading_case_failures(
                        line, text, forms, section_id if section_id in owned else None
                    )
                )
    # A line a placed inherited unit renders verbatim is the upstream's own spelling, which check 8
    # requires the renderer to keep unchanged, so this rule does not judge it.
    verbatim = verbatim_lines(candidate)
    authored_prose = prose([line for line in outside if line.strip() not in verbatim])
    offenders = sorted(
        word
        for word in set(LOWER_WORD.findall(authored_prose))
        if word in forms and forms[word] != word
    )
    if offenders:
        # Located to the first LLM-owned section whose own lowercased prose contains the word, never
        # a deterministic (renderer-owned) section: an abbreviation the renderer itself spells is a
        # renderer defect, not a repairable unit.
        llm_owned = {
            section.id for section in SEMANTIC_SHELL if section.owner != RENDERER_OWNER
        }
        section_prose = {
            section_id: prose(
                [line for line in text.splitlines() if line.strip() not in verbatim]
            ).lower()
            for section_id, text in section_texts(candidate.readme).items()
            if section_id in llm_owned
        }
        for word in offenders:
            located_in = next(
                (
                    sid
                    for sid, text in section_prose.items()
                    if re.search(rf"\b{word}\b", text)
                ),
                None,
            )
            failures.append(
                Failure(
                    "COMPOSING",
                    f"abbreviation {word!r} is not in its canonical form {forms[word]}",
                    located_in,
                )
            )
    failures.extend(_collapsed_section_failures(candidate.readme))
    failures.extend(_fence_and_spacing_failures(candidate))
    graphs = [
        body for language, body in fences(candidate.readme) if language == "mermaid"
    ]
    if len(graphs) > 1:
        failures.append(Failure("COMPOSING", "more than one At a Glance graph"))
    glance_text = section_texts(candidate.readme).get("at_a_glance", "")
    if glance_text.strip() and GLANCE_FENCE.sub("", glance_text, count=1).strip():
        # README_CONTRACT.md row 6: exactly one Mermaid fence and nothing else.
        failures.append(
            Failure(
                "COMPOSING",
                "At a Glance holds exactly one Mermaid fence and nothing else",
            )
        )
    # A narration phrase that is itself a SUPPORTED public symbol's name is the repository's own API;
    # one a placed or inherited upstream sentence already used is the upstream's vocabulary; one
    # inside a symbol's own docstring is the docstring's text. None of those is the pipeline talking.
    symbol_names = {
        fact.value.rsplit(".", 1)[-1].lower()
        for fact in candidate.facts.by_kind("public_symbol")
        if fact.polarity == "SUPPORTED"
    }
    inherited_prose = " ".join(
        fact.value.lower()
        for fact in candidate.facts.by_kind("inherited_unit")
        if fact.polarity == "SUPPORTED"
    )
    docstring_prose = " ".join(
        str((fact.attributes or {}).get("docstring") or "").lower()
        for fact in candidate.facts.by_kind("public_symbol")
        if fact.polarity == "SUPPORTED"
    )
    failures.extend(
        _narration_failures(
            candidate.readme,
            prose(outside),
            symbol_names,
            inherited_prose,
            docstring_prose,
        )
    )
    failures.extend(_reference_failures(candidate))
    visible, total = line_counts(candidate.readme)
    policy = candidate.policy
    # Collapsed content is unbounded; only visible lines count against the budget.
    if visible > policy.visible_lines_budget:
        failures.append(
            Failure(
                "PLANNING",
                f"{visible} visible lines of {total} exceed the visible budget "
                f"{policy.visible_lines_budget}",
            )
        )
    return failures


def _name_tail(canonical: str) -> frozenset[str]:
    """The lower-cased segments a canonical name carries after its FOSS segment, less "for":
    ``Aspose.GIS.FOSS for .Net`` -> ``{"net"}``."""
    segments = [part for part in re.split(r"[\s._-]+", canonical) if part]
    foss = next((i for i, part in enumerate(segments) if part.lower() == "foss"), None)
    tail = [] if foss is None else segments[foss + 1 :]
    return frozenset(part.lower() for part in tail if part.lower() != "for")


def canonical_name_pattern(canonical: str) -> re.Pattern[str]:
    """Every separator, case, and suffix variant of ``canonical``, built from it alone.

    The name splits into its alphanumeric segments (``Aspose.3D FOSS for .NET`` -> Aspose, 3D,
    FOSS, for, NET). A variant is those segments joined by any run of ``. - _`` or whitespace (or
    none), in any letter case, from the first through the FOSS segment, plus the trailing
    ``for <platform>`` segments as one optional all-or-nothing tail. A name without a FOSS segment
    must match whole.
    """
    segments = [part for part in re.split(r"[\s._-]+", canonical) if part]
    foss = next((i for i, part in enumerate(segments) if part.lower() == "foss"), None)
    head, tail = (
        (segments, []) if foss is None else (segments[: foss + 1], segments[foss + 1 :])
    )
    pattern = NAME_SEPARATOR.join(re.escape(part) for part in head)
    if tail:
        rest = NAME_SEPARATOR.join(re.escape(part) for part in tail)
        pattern += f"(?:{NAME_SEPARATOR}{rest})?"
    return re.compile(r"(?<![A-Za-z0-9])" + pattern + r"(?![A-Za-z0-9])", re.IGNORECASE)


def _is_technical_identifier(
    found: str,
    before: str,
    after: str,
    *,
    around: tuple[str, str] | None = None,
    tail: frozenset[str] = frozenset(),
) -> bool:
    """plans/idea.md: package names, import paths, namespaces and commands "may use their exact
    technical forms only where that technical identifier is itself the subject". A no-space spelling
    with a hyphen or underscore is a package, module or repository slug; any other no-space spelling
    is an identifier when a package/namespace cue sits beside it or it heads a longer dotted, slashed
    or scoped identifier. A continuation that spells the canonical name's own suffix is that name
    mangled, not a type. ``around`` is the same window read from the README with code-span backticks
    removed, and decides the continuation only."""
    if any(character.isspace() for character in found):
        return False
    if "-" in found or "_" in found:
        return True
    if IDENTIFIER_CUE_BEFORE.search(before) or IDENTIFIER_CUE_AFTER.match(after):
        return True
    near_before, near_after = around if around is not None else (before, after)
    if not (
        IDENTIFIER_CONTINUES.match(near_after)
        or IDENTIFIER_CONTINUED.search(near_before)
    ):
        return False
    segment = DOTTED_SEGMENT.match(near_after)
    return segment is None or segment.group(1).lower() not in tail


def canonical_name_failures(candidate: Candidate) -> list[Failure]:
    """BC-12: every product-identity position in the prose spells the registry's canonical product
    name exactly; no separator, case, or suffix variant of it. Code spans and fences are not judged:
    exact technical identifiers belong there.

    A misspelling inside a sentence a placed inherited unit carries verbatim is the upstream
    repository's own wording, which only reconciliation can revise with evidence (RECONCILING,
    naming the unit, the same ``_reference_failures`` pattern just above) -- S6 authoring never
    wrote that sentence and cannot change it. Measured live (aspose-cells-foss/Aspose.Cells-FOSS-
    for-Cpp, run 40687656250): this check hardcoded "COMPOSING" unconditionally, so the only real
    BC-12 finding this portfolio has produced so far routed to section_authoring with nothing in
    its own stage output to revise -- a no-op repair, rejected twice, exactly as this file's own
    docstring on ``_reference_failures`` already warns an unrouted check will produce."""
    canonical = product_name(candidate.entry)
    pattern = canonical_name_pattern(canonical)
    text = visible_prose(candidate.readme)
    tail = _name_tail(canonical)
    source = candidate.readme.splitlines()
    # A minimal probe of the pattern/technical-identifier logic alone (every existing BC-12 unit
    # test below this one) hands a bare entry+readme double with no plan, units, dispositions or
    # facts at all; placement is simply unknown there, so it degrades to the old COMPOSING-only
    # behavior rather than erroring, the same "unknown degrades, never crashes" rule this project
    # already applies to a missing toolchain or a cache miss.
    placed = (
        [
            (p.unit_id, normalized(p.text))
            for p in placements_of(candidate)
            if p.outcome == "placed"
        ]
        if all(hasattr(candidate, attr) for attr in ("plan", "units", "dispositions", "facts"))
        else []
    )
    failures: list[Failure] = []
    seen: set[tuple[str, str | None]] = set()
    for match in pattern.finditer(text):
        found = match.group(0)
        if found == canonical:
            continue
        # The prose is the README with each code span blanked to spaces of the same length, so a
        # match sits at the same column of the same line in the source.
        line = text.count("\n", 0, match.start())
        column = match.start() - (text.rfind("\n", 0, match.start()) + 1)
        row = source[line] if line < len(source) else ""
        around = (
            row[max(0, column - 24) : column].replace("`", ""),
            row[column + len(found) : column + len(found) + 24].replace("`", ""),
        )
        if _is_technical_identifier(
            found,
            text[max(0, match.start() - 24) : match.start()],
            text[match.end() : match.end() + 24],
            around=around,
            tail=tail,
        ):
            continue
        section = located(candidate.readme, text, match.start())
        if (found, section) in seen:
            continue
        seen.add((found, section))
        normalized_row = normalized(row)
        unit = next(
            (
                unit_id
                for unit_id, unit_text in placed
                if normalized_row and normalized_row in unit_text
            ),
            None,
        )
        if unit is not None:
            failures.append(
                Failure(
                    "RECONCILING",
                    f"{unit} is kept as written but spells the product name {found!r}, not "
                    f"the canonical {canonical!r}",
                    section,
                    unit=unit,
                )
            )
        else:
            failures.append(
                Failure(
                    "COMPOSING",
                    f"product name {found!r} is not the canonical name {canonical!r}",
                    section,
                )
            )
    return failures
