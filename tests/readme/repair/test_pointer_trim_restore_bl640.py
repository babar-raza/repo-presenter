"""BL-640: a restored paragraph whose only obstacle is the sentence pointing at a section this README does
not print is kept without that sentence (recorded on its disposition, R14), instead of being left as the
model's VERIFIED_REWRITE that dropped the command and the link standing beside the pointer.

Real data: ``inherited_unit:025.paragraph`` of aspose-pdf-foss/Aspose-PDF-FOSS-for-Go at the pinned
revision dfa75dbf (README 'Feature Showcase'), the shape hosted run 44943378148 failed on: 'BC-08
VERIFIED_REWRITE keeps the command `go run ./_examples/feature_showcase` but the candidate does not render
it' and 'BC-17 holds links `_examples/feature_showcase/main.go`', every settle round, nothing restorable."""

from __future__ import annotations

from repo_presenter.core.facts import Evidence, Fact, FactsDocument
from repo_presenter.readme.reconciliation.dispositions import dangling_pointers
from repo_presenter.readme.repair.restore_units import restore_lost_units
from repo_presenter.readme.validation.must_correct import DEGRADE_WITHHELD_KEY, withheld_form

UNIT = "inherited_unit:025.paragraph"
TEXT = (
    "[**docs/feature_showcase.pdf**](docs/feature_showcase.pdf) is a single 20-page PDF generated by\n"
    "[`_examples/feature_showcase`](_examples/feature_showcase/main.go) that walks nearly every\n"
    "capability above in one document. Cross-cutting metadata is set once and carried through the whole\n"
    "document. The showcase itself is deliberately left unencrypted so it previews inline on GitHub and\n"
    "opens in every viewer; encryption (RC4 / AES-128 / AES-256) is covered in\n"
    "[Encryption and Signing](#encryption-and-signing) below. Regenerate it locally with\n"
    "`go run ./_examples/feature_showcase`."
)
HOLDABLE = ("opening", "key_capabilities", "quick_start", "additional_examples", "development_testing")


def _fact(fact_id: str, value: str) -> Fact:
    return Fact(
        id=fact_id, kind="inherited_unit", value=value, evidence=(Evidence("README.md", None),),  # type: ignore[arg-type]
        polarity="SUPPORTED", attributes={"section": "Aspose.PDF FOSS for Go > Feature Showcase"},  # type: ignore[arg-type]
    )


def _facts(text: str = TEXT, unit: str = UNIT) -> FactsDocument:
    return FactsDocument(
        "aspose-pdf-foss/Aspose-PDF-FOSS-for-Go", "0" * 40,
        (_fact(unit, text), *(_fact(f"inherited_unit:09{i}.paragraph", f"Filler {i}.") for i in range(3))),
    )


def _dispositions(unit: str = UNIT) -> dict:
    return {
        "dispositions": [
            {
                "unit_id": unit, "disposition": "VERIFIED_REWRITE", "destination_section": "development_testing",
                "fact_ids": [], "rationale": "folded",
            }
        ]
    }


def test_the_pointer_sentence_alone_is_withheld_so_the_command_and_the_link_are_kept() -> None:
    skipped: list[dict[str, str]] = []
    new, changes = restore_lost_units(_dispositions(), _facts(), [UNIT], HOLDABLE, HOLDABLE, skipped=skipped)
    assert [c["unit_id"] for c in changes] == [UNIT] and skipped == []
    assert "encryption" in changes[0]["withheld"].lower()
    entry = new["dispositions"][0]
    assert entry["disposition"] in {"VERIFIED_PRESERVE", "PRESERVE_ATTRIBUTED"}
    printed = withheld_form(UNIT, TEXT, entry[DEGRADE_WITHHELD_KEY])
    assert "go run ./_examples/feature_showcase" in printed
    assert "(_examples/feature_showcase/main.go)" in printed
    assert "Encryption and Signing" not in printed and "deliberately left unencrypted" not in printed
    assert printed.startswith("[**docs/feature_showcase.pdf**]")  # everything else exactly as written
    assert "Cross-cutting metadata is set once" in printed
    assert dangling_pointers(new, _facts()) == []  # the withheld pointer points at nothing


def test_negative_control_a_unit_that_is_only_the_pointer_is_still_skipped() -> None:
    only = "Encryption options are covered in [Encryption and Signing](#encryption-and-signing) below."
    skipped: list[dict[str, str]] = []
    new, changes = restore_lost_units(_dispositions(), _facts(only), [UNIT], HOLDABLE, HOLDABLE, skipped=skipped)
    assert changes == [] and skipped == [{"unit_id": UNIT, "reason": "dangling_pointer"}]
    assert DEGRADE_WITHHELD_KEY not in new["dispositions"][0]


def test_negative_control_a_list_is_never_trimmed_by_this_lever() -> None:
    unit = "inherited_unit:025.list"
    text = "- Plain item.\n- Encryption is covered in [Encryption and Signing](#encryption-and-signing) below."
    skipped: list[dict[str, str]] = []
    new, changes = restore_lost_units(
        _dispositions(unit), _facts(text, unit), [unit], HOLDABLE, HOLDABLE, skipped=skipped
    )
    assert changes == [] and DEGRADE_WITHHELD_KEY not in new["dispositions"][0]


def test_negative_control_a_unit_without_a_pointer_is_restored_whole_with_nothing_withheld() -> None:
    text = TEXT.replace(
        "The showcase itself is deliberately left unencrypted so it previews inline on GitHub and\n"
        "opens in every viewer; encryption (RC4 / AES-128 / AES-256) is covered in\n"
        "[Encryption and Signing](#encryption-and-signing) below. ",
        "",
    )
    new, changes = restore_lost_units(_dispositions(), _facts(text), [UNIT], HOLDABLE, HOLDABLE, skipped=[])
    assert [c["unit_id"] for c in changes] == [UNIT] and "withheld" not in changes[0]
    assert DEGRADE_WITHHELD_KEY not in new["dispositions"][0]
