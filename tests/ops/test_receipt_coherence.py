"""Real negative-control tests for the 2026-11-04 receipt-integrity correction, demanded
directly by the owner's follow-up directive: 'A receipt does not automatically become
authoritative because its JSON says it was generated by gatecli.' These exercise
gateverify.receipt_is_coherent() and receipt_artifact_present() against exactly the five
scenarios the directive named: a forged positive receipt, missing negative-control evidence, a
changed acceptance checker (covered by the existing card_is_stale tests -- a changed checker
changes the card's hash), a missing artifact, and a changed card (same staleness mechanism).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "ops"))

import gateverify  # noqa: E402


def full_receipt(**overrides) -> dict:
    """A complete, schema-valid, internally-coherent ACCEPTED receipt -- the positive control
    every negative test below starts from and corrupts exactly one thing."""
    base = {
        "schema_version": 1,
        "card": "TC-001",
        "gate": "GATE0_AUTHORITY",
        "generated_by": "gatecli",
        "generated_at": "2026-11-04T00:00:00Z",
        "base_rev": "a" * 40,
        "head_rev": "a" * 40,
        "card_sha256": "b" * 64,
        "fingerprint": {"python": "3.13.0", "platform": "test"},
        "scope": {"ok": True, "changed_paths": [], "violations": [], "evaluated": True},
        "runs": [
            {"run": 1, "checks": [{"command": "x", "exit_code": 0, "duration_s": 0.1,
                                    "stdout_sha256": "c" * 64}], "all_passed": True},
            {"run": 2, "checks": [{"command": "x", "exit_code": 0, "duration_s": 0.1,
                                    "stdout_sha256": "c" * 64}], "all_passed": True},
        ],
        "negative_control": {
            "kind": "mutate", "patch": "echo x", "patch_sha256": "d" * 64,
            "applied": True, "patch_applied_failed": True,
            "exit_codes": [1], "tree_changed": ["some/file.py"],
        },
        "accepted": True,
        "reason": "all gates passed",
    }
    base.update(overrides)
    return base


def test_positive_control_a_genuinely_coherent_receipt_has_no_problems():
    assert gateverify.receipt_is_coherent(full_receipt()) == []


def test_forged_positive_receipt_with_no_clean_runs_rejected():
    """A hand-edited receipt that sets accepted=True without the checks actually having passed
    twice clean -- the core 'the JSON says so' forgery the directive described."""
    forged = full_receipt(runs=[
        {"run": 1, "checks": [{"command": "x", "exit_code": 1, "duration_s": 0.1,
                                "stdout_sha256": "c" * 64}], "all_passed": False},
        {"run": 2, "checks": [{"command": "x", "exit_code": 1, "duration_s": 0.1,
                                "stdout_sha256": "c" * 64}], "all_passed": False},
    ])
    problems = gateverify.receipt_is_coherent(forged)
    assert any("two identical clean passes" in p for p in problems)


def test_forged_positive_receipt_with_scope_violation_rejected():
    forged = full_receipt(scope={"ok": False, "changed_paths": ["x"], "violations": ["bad"], "evaluated": True})
    problems = gateverify.receipt_is_coherent(forged)
    assert any("scope.ok" in p for p in problems)


def test_missing_negative_control_evidence_rejected_applied_false():
    """accepted=True but the negative control was never actually applied -- the falsifier never
    ran, so nothing was proven."""
    forged = full_receipt(negative_control={
        "kind": "mutate", "patch": "echo x", "patch_sha256": "d" * 64,
        "applied": False, "patch_applied_failed": False, "exit_codes": [], "tree_changed": [],
    })
    problems = gateverify.receipt_is_coherent(forged)
    assert any("negative_control.applied is not True" in p for p in problems)


def test_missing_negative_control_evidence_rejected_vacuous():
    """accepted=True, negative control applied, but patch_applied_failed=False -- the exact
    'VACUOUS CHECKS' case do_verify itself refuses; a forged receipt could still claim
    accepted=True while recording this contradiction."""
    forged = full_receipt(negative_control={
        "kind": "mutate", "patch": "echo x", "patch_sha256": "d" * 64,
        "applied": True, "patch_applied_failed": False, "exit_codes": [0], "tree_changed": ["x"],
    })
    problems = gateverify.receipt_is_coherent(forged)
    assert any("patch_applied_failed is not True" in p for p in problems)


def test_missing_negative_control_evidence_rejected_empty_tree_changed():
    """accepted=True, applied=True, patch_applied_failed=True, but tree_changed is empty -- no
    actual evidence anything was mutated. do_verify's own code treats an unmutated tree as
    'applied=False' (see run() in gatectl's negative-control handling), so a receipt showing
    this combination could only arise from hand-editing, not a real verify run."""
    forged = full_receipt(negative_control={
        "kind": "mutate", "patch": "echo x", "patch_sha256": "d" * 64,
        "applied": True, "patch_applied_failed": True, "exit_codes": [1], "tree_changed": [],
    })
    problems = gateverify.receipt_is_coherent(forged)
    assert any("tree_changed is empty" in p for p in problems)


def test_malformed_receipt_fails_schema_and_is_incoherent():
    """A receipt missing a required field entirely (schemas/receipt.schema.json) must be
    rejected outright -- schema validity is the first, cheapest coherence check."""
    forged = full_receipt()
    del forged["fingerprint"]
    problems = gateverify.receipt_is_coherent(forged)
    assert any("schema violation" in p for p in problems)


def test_wrong_generator_rejected():
    forged = full_receipt(generated_by="a-human-typed-this")
    problems = gateverify.receipt_is_coherent(forged)
    assert any("generated_by" in p for p in problems)


def test_not_accepted_receipt_is_never_flagged_incoherent_merely_for_failing():
    """Positive control: a perfectly honest NOT-accepted receipt (clean runs correctly failed,
    negative control correctly skipped) must not be flagged incoherent just because it's not
    accepted -- incoherence is specifically about a receipt that CLAIMS accepted=True without
    the evidence to back it, not about failing cards in general."""
    honest_failure = full_receipt(
        accepted=False, reason="checks failed",
        runs=[
            {"run": 1, "checks": [{"command": "x", "exit_code": 1, "duration_s": 0.1,
                                    "stdout_sha256": "c" * 64}], "all_passed": False},
            {"run": 2, "checks": [{"command": "x", "exit_code": 1, "duration_s": 0.1,
                                    "stdout_sha256": "c" * 64}], "all_passed": False},
        ],
        negative_control={
            "kind": "mutate", "patch": "echo x", "patch_sha256": "d" * 64,
            "applied": False, "patch_applied_failed": False, "exit_codes": [], "tree_changed": [],
        },
    )
    assert gateverify.receipt_is_coherent(honest_failure) == []


def test_missing_artifact_detected(tmp_path, monkeypatch):
    """A receipt.json with no sibling stdout.log -- the directive's 'missing artifact' scenario.
    receipt_artifact_present() must say so."""
    gate, cid = "GATE0_AUTHORITY", "TC-999"
    d = tmp_path / "evidence" / "build" / gate / cid
    d.mkdir(parents=True)
    (d / "receipt.json").write_text(json.dumps(full_receipt()), encoding="utf-8")
    monkeypatch.setattr(gateverify, "EVIDENCE", tmp_path / "evidence")
    assert gateverify.receipt_artifact_present(gate, cid) is False
    (d / "stdout.log").write_text("log", encoding="utf-8")
    assert gateverify.receipt_artifact_present(gate, cid) is True


def test_incoherent_receipt_does_not_count_as_accepted_in_compute_rows():
    """End-to-end through compute_rows(): a forged-looking receipt (accepted=True, but the
    negative control was vacuous) must land the card in INCOHERENT_RECEIPT, not ACCEPTED, and
    must not count toward a downstream dependency's eligibility."""
    cards = {
        "TC-A": {"id": "TC-A", "gate": "G", "depends_on": []},
        "TC-B": {"id": "TC-B", "gate": "G", "depends_on": ["TC-A"]},
    }
    forged = full_receipt(card="TC-A", negative_control={
        "kind": "mutate", "patch": "echo x", "patch_sha256": "d" * 64,
        "applied": True, "patch_applied_failed": False, "exit_codes": [0], "tree_changed": ["x"],
    })
    honest = full_receipt(card="TC-B")
    raw = {
        "TC-A": {"receipt": forged, "attempt": 0, "stale": False,
                 "incoherent": True, "incoherent_reasons": ["patch_applied_failed is not True"]},
        "TC-B": {"receipt": honest, "attempt": 0, "stale": False,
                 "incoherent": False, "incoherent_reasons": []},
    }
    rows, accepted = gateverify.compute_rows(cards, raw, dispatched=set(), attempts={}, latest_kind={})
    by_id = {r["id"]: r for r in rows}
    assert by_id["TC-A"]["status"] == "INCOHERENT_RECEIPT"
    assert "TC-A" not in accepted
    assert by_id["TC-B"]["status"] == "AWAITING_PREREQUISITE"
    assert "TC-B" not in accepted
    assert "TC-A" in gateverify.ready_cards_from_rows(rows)  # re-attemptable, not stuck
